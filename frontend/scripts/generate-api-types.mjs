import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const frontendRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = path.resolve(frontendRoot, '..')
const inputPath = path.join(repoRoot, 'docs/openapi/openapi.json')
const outputPath = path.join(frontendRoot, 'src/api/generated/openapi.ts')
mkdirSync(path.dirname(outputPath), { recursive: true })
const schema = JSON.parse(readFileSync(inputPath, 'utf8'))

function tsType(definition) {
  if (definition.type === 'null') return 'null'
  if (definition.enum) return definition.enum.map((value) => JSON.stringify(value)).join(' | ')
  if (definition.$ref) return `components[${JSON.stringify(definition.$ref.split('/').at(-1))}]`
  if (definition.anyOf || definition.oneOf) return (definition.anyOf ?? definition.oneOf).map(tsType).join(' | ')
  if (definition.type === 'array') return `Array<${tsType(definition.items ?? {})}>`
  if (definition.type === 'integer' || definition.type === 'number') return 'number'
  if (definition.type === 'boolean') return 'boolean'
  if (definition.type === 'string') return 'string'
  if (definition.type === 'object' || definition.properties) return 'Record<string, unknown>'
  return 'unknown'
}

const schemas = schema.components?.schemas ?? {}
const required = new Map(Object.entries(schemas).map(([name, value]) => [name, new Set(value.required ?? [])]))
const schemaDeclarations = Object.entries(schemas).map(([name, value]) => {
  const properties = Object.entries(value.properties ?? {}).map(([key, definition]) => {
    const optional = required.get(name).has(key) ? '' : '?'
    const nullable = definition.nullable ? ' | null' : ''
    return `    ${JSON.stringify(key)}${optional}: ${tsType(definition)}${nullable}`
  })
  return `  ${JSON.stringify(name)}: {\n${properties.join(';\n')}\n  }`
})

const operations = []
for (const [route, methods] of Object.entries(schema.paths ?? {})) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue
    operations.push(`  ${JSON.stringify(`${method.toUpperCase()} ${route}`)}: {\n    operationId: ${JSON.stringify(operation.operationId ?? '')}\n  }`)
  }
}

const output = `// Generated by frontend/scripts/generate-api-types.mjs from docs/openapi/openapi.json. Do not edit.\nexport interface components {\n${schemaDeclarations.join(';\n')}\n}\n\nexport interface operations {\n${operations.join(';\n')}\n}\n\nexport type OperationKey = keyof operations\n`
writeFileSync(outputPath, output, 'utf8')
console.log(`Generated ${Object.keys(schemas).length} schemas and ${operations.length} operations.`)
